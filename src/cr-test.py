def show_tracks (prefix, L, R, T):
	S = [[] for t in range (max (T))]
	LD = cn_density (L, R, max (R) + 1)

	for n, t in enumerate (T):
		if n > 0 and t > 0:
			S[t-1].append (n)

	for track in S:
		track.sort (key = lambda n : L[n])

	print (prefix, S, '->', len (S), '/', max (LD))

def test_lec (U, D):
	L, R, T = cr_lec (U, D)

	show_tracks ('LEC =', L, R, T)

def test_leb (U, D):
	L, R, T = cr_leb (U, D)

	show_tracks ('LEB =', L, R, T)

